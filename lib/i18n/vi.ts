const ORDERED = Object.entries(TRANSLATIONS).sort((a, b) => b[0].length - a[0].length);

export function viText(value: unknown, fallback = "Sản phẩm") {
  if (value === null || value === undefined) return "";
  let output = String(value);
  for (const [source, target] of ORDERED) output = output.split(source).join(target);
  output = output
    .replace(/(\d{2})\.(\d{2})\([^)]+\)/g, "$1.$2")
    .replace(/내일/g, "Ngày mai")
    .replace(/원/g, "đ")
    .replace(/[가-힣]+/g, "")
    .replace(/\s{2,}/g, " ")
    .replace(/\s+([,.:;!?])/g, "$1")
    .trim();
  return output || fallback;
}

export function viCategory(value: unknown) {
  return viText(value, "Danh mục");
}

export function viProduct(value: unknown) {
  const output = viText(value, "Sản phẩm")
    .replace(/〈\s*〉/g, "")
    .replace(/\(\s*\)/g, "")
    .replace(/\s{2,}/g, " ")
    .trim();
  return output && output !== "Nhạc kịch" ? output : "Sản phẩm nổi bật";
}

export function viHtml(value: unknown) {
  return viText(value, "");
}
